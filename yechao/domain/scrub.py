"""出网脱敏 —— 抹掉能指到具体人的东西。

## 要防什么

把群聊原文发给模型之前，抹掉能指到具体人的东西：号码、账号、邮箱、姓名。

**为什么不能一刀切、在入口就抹掉姓名**：

姓名在**本机内部**是重要信号 —— 群昵称常带「22-3班学习委员林小满」这类角色与
班级，是判断「这条通知是不是官方发的」最可靠的依据。在入口就抹掉，等于把最有
用的信号先废掉。

所以边界画在**出网那一刻**，不是入口。

## 判据一：**凭什么**认定一个数字串是号码

先回答这个问题，再谈阈值。三个**互相独立**的信号，各自回答「它是什么」：

**信号 A：形态符合某条号码编制规则。**
手机号是「11 位、首位 1、次位 3–9」—— 这是**号码编制的事实**
（10x / 11x / 12x 是服务号段，移动号段从 13x 起），不是本项目试出来的阈值。
形态自明 ⇒ **不需要任何上下文**。

**信号 B：长度超出本语料里一切非标识符的数字。**
本语料里最长的非标识符数字是：日期 8 位（`20270315`）、Unix 时间戳 10 位；
金额 ≤ 6 位，序号 / 楼层 1–4 位。
⇒ **≥ 12 位**的数字串**不可能是它们中的任何一个**。
（11 位被排除在外，因为那是手机号的地盘，由信号 A 管。）

**信号 C：邻近的词把它命名为标识符。**
5–11 位的数字串本身看不出是什么 —— 它与金额、房号、课程序号、订单号
严重重叠（`8200` 是报名费还是群号？纯看数字分不出来）。
但它左边如果紧挨着一个**命名它的词**，那个词就把它定性了。

⇒ **A、B 各自单独就够；C 必须有上下文。**
这就是「强判据 / 模糊判据」分档的**依据** —— 分档不是因为「严格程度不同」，
而是因为**信号自己够不够**。所以：

  · A / B / 邮箱 ⇒ 一律抹，不看上下文（形态自明）。
  · C ⇒ 只在触发词在场时抹（形态不自明）。

**误伤与漏抹的取舍**：分档之后，两档的取向**不同**，这是刻意的。
  · 强判据误伤极少（符合号段编制的 11 位数字串几乎只有手机号一种可能）⇒ 一律抹。
  · 模糊判据误伤代价高（抹掉一条真金额，模型就读不到金额了，
    而金额是条目要填的字段）⇒ 只在触发词在场时抹。
  · 漏抹的代价是**真号码出网**，比误伤更重 ⇒ 触发词表取**宽进**取向：
    宁可多触发几次（多抹一个看起来像号码的数字），不可漏。

## 边界断言：号码必须**自成一段**

一条号码判据只回答「这个串是不是号码」，还要回答「它**到哪里为止**」。
两条判据的边界都不能是数字：左邻与右邻都不能是数字。

为什么必须：源文写 `820000177000010019`（18 位），里面**含**一个 11 位的
手机号形状。若判据不带边界，手机号规则会在长串**中间**匹配一段，
把长串从中间切开 —— 抹掉中间 11 位，两边各留一截残渣。

※ **实测（改前）：两个边界同时在时，这件事不会发生。**
长串内部的 11 位两侧都是数字，左侧的「前一字符不是数字」与右侧的
「后一字符不是数字」两条断言各挡住一个方向，
所以手机号判据在长串里**根本匹配不上**。
⇒ 由此得到两条结论：
  1. 「长数字串要排在手机号前面」这个**顺序**，**不是**被这条失败模式逼出来的
     （边界已经把它挡住了）。它的真实理由是另一条：**掩码要取最大的那个 token**
     —— 见 `_mask_numbers`。
  2. 一个**结构事实**：`_LONG_DIGITS`（≥12 位）与 `_PHONE`（11 位）
     **互不相交**，所以这两条之间的先后顺序不影响结果。
     `tests/domain/test_scrub.py` 里有一条用例把这件事钉住。

## 模糊判据的触发词：按**词**取

真实语料里「群号」的写法：`群 820000001`、`入群 820000002`、
`同乡群：820000003`、`q群 820000004`……

枚举写法枚举不完。取它们的共同点：数字左边紧挨着一个**命名标识符的词**。
所以触发词是一张**词**表，不是一张**字**表。

※ **触发词与数字之间只许夹非词字符**（空白、冒号、`#`、`-`）。
这一条把「夹了别的汉字」挡在外面，也正是误伤检查的落点：

  · `群公告 820000001` —— `群` 与数字之间隔着「公告」（汉字）⇒ **不触发**。
    它是一条公告，不是群号。
  · `群力 660 元` —— 触发词 `群` 后面紧跟的是汉字 `力` ⇒ **不触发**。
    这是「按字取」最容易误伤的形状，判据必须挡住它。

⇒ 推论：`群号` 必须是词表里的**一个词** —— `号` 是这个词的一部分，
**不是分隔符**。写这条正则时漏过它（把 `群` 当触发词、又没把 `号` 算进词里），
测试当场红 —— 那正是那条用例存在的理由。

## URL 里抹什么：抹强判据，**显式**豁免模糊判据

链接里的数字不该抹，否则短链就废了。但**强判据不在此列**：

`?phone=17700001001` 里的那个号码**仍然是手机号** —— 它指得到人，
与它出现在哪里无关。所以：

  · 手机号 / 长数字串 / 邮箱 ⇒ URL 里**照样抹**（形态自明，不依赖上下文）
  · 触发词规则 ⇒ URL **整段豁免**（`_mask_account` 里显式跳过 URL 区间）

**为什么模糊判据要豁免**：触发词规则问的是「左边那个词把它命名成了什么」。
在 URL 里，那串数字**不是被命名的标识符，它是一个定位符的一部分** ——
抹掉它就等于把链接打烂，而链接是用户自己选择要写出去的地址。

※ **这条豁免必须写成代码，不能靠「反正 URL 里没有汉字」**：
触发词表里有一个 ASCII 词（`qq`），而 `https://example.test/qq820000001`
这样的路径里，触发词与数字**都在 URL 里**。早先这里只有一句推论
（「中文不能直接出现在 URL 里 ⇒ 触发词不会出现在 URL 里」），
那句话对 `qq` **不成立** —— 一条**看起来在起作用、其实没有**的判据。
所以豁免改成显式跳过 URL 区间。

**URL 的右边界**：URL 里能出现什么字符？RFC 3986 的 unreserved + reserved
全是 **ASCII**；中文**不能**直接出现在 URL 里，必须被百分号编码
（`%E4%B8%AD`）。⇒ 右边界就是第一个非 URL 字符 —— 在中文语料里通常是
第一个汉字。若写成「从 http 一直到空白」，它会一路吞掉后面的正文，
而手机号就藏在正文里（见 `_URL_CHARS`）。

## 姓名：保留角色、抹掉人名本体

群昵称 `22-3班学习委员林小满` 里，`22-3班学习委员` 是**要保留的信号**，
`林小满` 才是要抹的**个人标识符**。

判据的来源是**本机已有的名单**（群成员昵称表）—— 从昵称里解析出人名集合，
然后对出网文本做**精确子串替换**。

※ 这条边界**证明不了**「不含任何姓名」：模型自己补出一个不在名单上的名字，
精确子串替换拦不住。这是本架构**已知的**边界，不许在界面上简化成
「无隐私风险」。

## 为什么要返回 `ScrubReport` 而不是一个字符串

出网审计（主叙事「可证伪的隐私」）要能回答「那一刻送出去的到底是什么」。
只返回字符串的话，调用方没有任何东西可记。

※ 而且报告里必须带 **`names_checked`（本轮实际比对了几个姓名）**：
「查过了、没命中」与「**根本没查**」在结果里长得一模一样
输入是空的名单时，「命中 0」的含义是
**「没查」**，不是「通过」。
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field

from yechao.domain.textnorm import normalize

#: 号码被遮蔽成这个。前端 `num_placeholders` 数它的处数。
NUM_PLACEHOLDER = "<号码>"
#: 姓名被抹成这个。前端 `name_placeholders` 数它的处数。
NAME_PLACEHOLDER = "<姓名>"

# ── 边界 ────────────────────────────────────────────────────────────

#: 「不是数字」的判据。
#: ※ Python 的 `\d`（str 模式）本来就匹配 **Unicode 十进制数字**
#: （类别 `Nd`，含全角 `０-９`），所以它不需要额外照顾全角数字 ——
#: 早先这里挂过一个 `_is_number_char()` 辅助函数，理由是「`\d` 会漏掉全角」，
#: **那个前提是错的**，函数也从没被调用过。一个命中不了的判据比没有更糟，删掉。
_NOT_DIGIT = r"(?<!\d)"
_NOT_DIGIT_AFTER = r"(?!\d)"


# ── 强判据 ──────────────────────────────────────────────────────────

#: 手机号：**信号 A**（形态符合号段编制）。
#: · 11 位、首位 `1`、次位 `[3-9]` —— 见模块 docstring「信号 A」。
#:   次位用 `[3-9]` 而不是 `\d`：`10x`/`11x`/`12x` 是**服务号段**，
#:   不是移动号段。收紧这里降低误伤，而 11 位这个长度本身很少被别的东西撞上。
#: · 分组分隔符：号码常写成 `177 0000 1001` 或 `177-0000-1001`
#:   —— 那是**同一个号码的另一种写法**，漏掉它就等于让一个手机号原样出网。
#:   所以允许每组之间有一个空格 / 制表符 / 连字符。
#:   ※ 只允许一个，且不含换行：换行是排版，不是号码的一部分。
_PHONE = re.compile(
    _NOT_DIGIT + r"(1[3-9]\d[ \t\-]?\d{4}[ \t\-]?\d{4})" + _NOT_DIGIT_AFTER
)

#: 长数字串：**信号 B**（长度超出本语料里一切非标识符数字），≥ 12 位。
#: 12 的来历见模块 docstring「信号 B」：日期 8 位、时间戳 10 位是上限。
#: ※ **贪婪**匹配（`\d{12,}`）：长串要**整条**被吃掉 —— 掩码单元取最大的
#: 那个 token，而不是它里面碰巧像手机号的那一段。
_LONG_DIGITS = re.compile(_NOT_DIGIT + r"(\d{12,})" + _NOT_DIGIT_AFTER)

#: 邮箱。※ 刻意**不用**过于宽松的 `\S+@\S+`：那会把 `见@林小满` 这类误伤。
#: 要求 local 与 domain 都只含邮箱合法字符，且 domain 至少有一个点。
_EMAIL = re.compile(
    r"(?<![\w.+-])"
    r"([A-Za-z0-9._%+-]+@[A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)+)"
    r"(?![\w-])"
)

# ── 模糊判据：**命名标识符的词** + 数字 ──────────────────────────────

#: **信号 C** 的词表：出现在数字左边、把那个数字**命名为一个标识符**的词。
#:
#: ※ 是**词**表，不是字表。`群号` 与 `群` 都要在里面 ——
#: 「号」是 `群号` 这个词的一部分，**不是**触发词与数字之间的分隔符。
#: 只放 `群` 而把 `号` 当分隔符，是同一个意思的另一种写法；
#: 但那样一来「分隔符里为什么允许一个汉字」就再也解释不清了。
#:
#: 词表取**宽进**取向（多触发几次的代价低于漏抹），但只收
#: 「在语料里真的用来命名一个标识符」的说法 —— 不收泛泛的名词。
_ACCOUNT_TRIGGER_WORDS = ("群号", "群", "qq", "扣扣", "q群")

#: 触发词与数字之间允许的**非词字符**：空白、冒号、`#`、`-`。
#: ※ **只允许非词字符** —— 这一条就是「不许夹别的汉字」：
#: `群公告 820000001` 里的「公告」是词字符，于是 `群` 与数字被隔开 ⇒ 不触发。
_SEP = r"[\s:：#\-#]*"

#: 触发词在场时，抹 5–11 位数字。
#: · 下界 5：更短的数字（房号、课程序号、楼层、金额）与标识符重叠太严重，
#:   没有触发词也到处都是；5 位以上才谈得上「一个具体的标识」。
#: · 上界 11：与手机号同宽 —— 再长就走**信号 B**（长数字串）那条判据了，
#:   两条判据在 12 位上接住。
_ACCOUNT_AFTER_TRIGGER = re.compile(
    r"(?:"
    + "|".join(_ACCOUNT_TRIGGER_WORDS)
    + r")"
    r"(" + _SEP + r")"
    r"(" + _NOT_DIGIT + r"(\d{5,11})" + _NOT_DIGIT_AFTER + r")",
    re.IGNORECASE,
)

# ── URL ─────────────────────────────────────────────────────────────

#: URL 的**字符集**。RFC 3986 的 unreserved + reserved + `%`。
#: ※ 这里**不含**任何中文字符 —— 中文不能直接出现在 URL 里，必须被编码成
#: `%XX`。所以扫描到第一个非此集合的字符就是 URL 的右边界。
_URL_CHARS = r"[A-Za-z0-9\-._~:/?#\[\]@!$&'()*+,;=%]"

#: 整条 URL。
_URL = re.compile(r"(?:https?://|www\.)" + _URL_CHARS + r"+", re.IGNORECASE)


@dataclass
class ScrubHit:
    """一处命中。

    ## ※ `text` 字段是**内存里的临时值**，审计绝不存它

    它存在是因为**调用方需要知道抹掉的是什么**：指标脚本要拿它跟真值比，
    自检要拿它断言「该抹的抹了」。

    ※ 而 `start` / `end` 是在**替换过程中**的坐标 —— 替换从右往左做，
    但多个模式串行执行，所以那两个值指向的是**当时那一段文本**的位置，
    而**不是原文**的坐标。第一版没有 `text` 字段，指标脚本拿 `h.start`
    去切原文，切出来的是 `<号码>认领。` 这种垃圾 ——
    于是它报了 5/7 的召回与 100% 的误伤，**两个错得看起来合理的数**。

    ⇒ 现在把**被抹掉的原文**直接带上（`text`），调用方不用猜坐标。

    ※ **但审计归档只允许白名单里的键**（`audit_log.ALLOWED_KEYS`），
    里面没有 `text` —— 所以「记录里不存内容」这条仍然成立。
    这两件事不矛盾：**内存里需要它，磁盘上不需要**。
    """

    kind: str  # "phone" | "long_digits" | "email" | "account" | "name"
    start: int
    end: int
    #: 被抹掉的那段原文。※ 只活在内存里，不进审计归档。
    text: str = ""


@dataclass
class ScrubReport:
    """出网脱敏的**可证伪记录**。

    它是「那一刻送出去的到底是什么」这句承诺的**机械证据**

    ※ 它**不存内容** —— 见 `ScrubHit`。
    """

    hits: list[ScrubHit] = field(default_factory=list)
    #: 本轮实际比对了几个姓名。
    #: ※ **这个字段是「查了没命中」与「根本没查」的唯一区分点**
    #: 没有它，名单为空时的「命中 0」会被
    #: 读成「通过」，而真相是「没查」。
    names_checked: int = 0
    #: 被遮蔽的号码处数。
    num_placeholders: int = 0
    #: 被抹掉的姓名处数。
    name_placeholders: int = 0

    @property
    def ok(self) -> bool:
        return not self.hits

    def __bool__(self) -> bool:
        return bool(self.hits)


# ── 号码遮蔽 ────────────────────────────────────────────────────────


def _mask_numbers(text: str) -> tuple[str, list[ScrubHit]]:
    """抹号码。**强判据与模糊判据都在这条流水线上。**

    顺序的判据只有一条：**掩码单元取最大的那个 token。**

    1. **邮箱先抹**。一个邮箱**包含着**数字（`student17700001001@example.test`）。
       若先抹手机号，邮箱会被从中间切开 —— 抹掉中间那段、域名留在原地，
       而邮箱**整体**才是那个指得到人的标识符。
       （实测改前正是这个症状：`student<号码>@example.test`。）
    2. **长数字串**（≥12 位）：它是自己那一整段，掩码单元就是它自己。
    3. **手机号**：同上。
       ※ 2 与 3 **互不相交**（12 位以上 vs 11 位），所以这两条谁先谁后
       都不影响结果 —— 它们之间不存在「谁切开谁」的问题，
       因为两侧的数字边界断言已经让手机号在长串里匹配不上了。
    4. **触发词规则放最后**：它依赖**周围的文本**（左边那个词），
       而前面几步的替换会改变周围文本。放最后保证它看到的是**原文的上下文**。
       （前面抹出的 `<号码>` 里没有数字，也不会反过来误触发它。）

    替换是**从右往左**做的：这样命中位置在替换过程中不会失效
    （从左往右替换会让后面的位置整体偏移）。
    """
    hits: list[ScrubHit] = []

    def _apply(pattern: re.Pattern[str], kind: str, group: int, cur: str) -> str:
        matches = list(pattern.finditer(cur))
        for m in reversed(matches):
            s, e = m.span(group)
            # ※ 在**替换之前**取被抹掉的那段 —— 这是 `text` 的唯一来源。
            hits.append(ScrubHit(kind=kind, start=s, end=e, text=cur[s:e]))
            cur = cur[:s] + NUM_PLACEHOLDER + cur[e:]
        return cur

    out = _apply(_EMAIL, "email", 1, text)
    out = _apply(_LONG_DIGITS, "long_digits", 1, out)
    out = _apply(_PHONE, "phone", 1, out)
    out, account_hits = _mask_account(out)
    hits.extend(account_hits)
    return out, hits


def _mask_account(text: str) -> tuple[str, list[ScrubHit]]:
    """**触发词 + 数字** → 抹数字。

    ※ 这条与上面几条不同：它要**保留触发词本身**（「群」「群号」是有效信息，
    抹了周围的词就断了），只抹数字。

    实现是逐字符扫而不是 `re.sub` —— 因为要保留捕获组 1（分隔符）与触发词，
    而 `re.sub` 的回调里拿不到「匹配起点之前的那个字」。

    ※ **URL 区间整段跳过**（见模块 docstring「URL 里抹什么」）：
    在 URL 里那串数字是一个定位符的一部分，不是被命名的标识符；
    抹掉它只会把链接打烂。**这条豁免是显式的**，不靠「URL 里没有汉字」。
    """
    hits: list[ScrubHit] = []
    out: list[str] = []
    url_spans = [m.span() for m in _URL.finditer(text)]

    def _in_url(pos: int) -> bool:
        return any(s <= pos < e for s, e in url_spans)

    i = 0
    while i < len(text):
        if _in_url(i):
            out.append(text[i])
            i += 1
            continue
        m = _ACCOUNT_AFTER_TRIGGER.match(text, i)
        if m:
            # m.group(0) = 触发词 + 分隔符 + 数字
            digit_start = m.start(2)
            digit_end = m.end(2)
            out.append(text[i:digit_start])
            hits.append(ScrubHit(
                kind="account", start=digit_start, end=digit_end,
                text=text[digit_start:digit_end],
            ))
            out.append(NUM_PLACEHOLDER)
            i = digit_end
        else:
            out.append(text[i])
            i += 1
    return "".join(out), hits


# ── 姓名遮蔽 ────────────────────────────────────────────────────────


def mask_names(text: str, names: list[str] | tuple[str, ...]) -> tuple[str, list[ScrubHit], int]:
    """把名单里的姓名精确子串替换成 `<姓名>`。

    返回 `(抹过的文本, 命中列表, 实际比对了几个姓名)`。

    ※ **按长度从长到短替换**：名单里同时有「林小满」与「林小满秋」时，
    先替换短的会把「林小满秋」切成「<姓名>丰」。从长到短保证最长的那个先被
    吃掉。

    ※ **返回 `names_checked` 而不是「命中数」**：调用方要能把「查过了、
    没命中」与「根本没查」分开。传进来空名单时，本函数做的事是**没查**，
    而它返回的命中数同样是 0 —— 两个 0 长得一模一样，只有比对过的对象数
    能把它们分开。
    """
    # ※ **先规范化再比**：`张<U+200B>三` 在模型眼里就是 `林小满`，
    # 而调用方可能直接调本函数（不经 `scrub()`）。不在这里收敛的话，
    # 绕过手法只在「恰好走了 `scrub()` 那条路」时被挡住 ——
    # 那是一个**取决于调用点**的判据，而那种判据最容易在新增调用点时失效。
    text = normalize(text)
    names = [normalize(n) for n in names]

    # 去重 + 丢掉过短的（单字姓名误伤极大：「王」「李」在中文里满地都是）
    unique = {n for n in names if n and len(n) >= 2}
    ordered = sorted(unique, key=len, reverse=True)

    hits: list[ScrubHit] = []
    out = text
    for name in ordered:
        if name not in out:
            continue
        # 收集所有出现位置（在**已替换过的**串上找，所以位置是当前串的）
        idx = 0
        while True:
            found = out.find(name, idx)
            if found < 0:
                break
            start, end = found, found + len(name)
            hits.append(ScrubHit(kind="name", start=start, end=end, text=out[start:end]))
            out = out[:start] + NAME_PLACEHOLDER + out[end:]
            idx = start + len(NAME_PLACEHOLDER)

    return out, hits, len(unique)



#: 昵称里常见的角色/班级前缀词。※ 拆的是**前缀**，不是所有位置 ——
#: 名字里也可能含这些字（「王老师」是名字的一部分吗？不一定）。
#: 取「从头剥」这个保守取向：剥不到就保留原名，不猜。
_NICK_PREFIX_WORDS = (
    "班主任助理", "班主任", "辅导员助理", "辅导员", "学习委员", "生活委员",
    "体育委员", "团支书", "班长", "学委", "社长", "会长", "部长", "主席",
    "教务员", "助理", "主任", "处长", "院长", "老师", "教授", "管理员",
    "班助", "导员", "官方号", "官方", "通知号",
)


def _strip_nick_prefix(nick: str) -> str | None:
    """从群昵称里剥出**人名本体**。剥不出来就返回 None（不猜）。

    ※ 顺序：先剥**班级前缀**（`22-1班`、`2022级`），再从**头**剥角色词。
    这个顺序是问题域决定的：角色词总是紧贴人名的左边，而班级在最外面。
    """
    import re as _re

    s = nick.strip()
    if not s:
        return None
    # 班级前缀：`22-1班` / `2022级` / `高一(3)班`
    s = _re.sub(r"^[\d\s\-]*(?:级|班|届)[\s\-]*", "", s)
    s = _re.sub(r"^\d{2,4}[-级]?\d*\s*", "", s)
    # 角色词：从长到短试，剥掉一个就停（不连续剥，避免把名字本身剥掉）
    for w in sorted(_NICK_PREFIX_WORDS, key=len, reverse=True):
        if s.startswith(w):
            s = s[len(w):].strip()
            break
    # ※ 剥完还太短 ⇒ **不猜**。一个字的「名字」在中文里满地都是。
    return s if len(s) >= 2 else None


def _expand_names(names: list[str]) -> list[str]:
    """名单 = 完整昵称 ∪ 从昵称里剥出的人名本体。

    ※ **两样都留**：完整昵称也可能出现在正文里（比如引用了一条消息头），
    而人名本体是正文里的常态。只留一样都会漏。
    """
    seen: set[str] = set()
    for n in names:
        seen.add(n)
        body = _strip_nick_prefix(n)
        if body:
            seen.add(body)
    return sorted(seen)



# ── 对外入口 ────────────────────────────────────────────────────────


def scrub(
    text: str,
    names: list[str] | tuple[str, ...] = (),
    *,
    known_uins: list[int] | tuple[int, ...] = (),
) -> tuple[str, ScrubReport]:
    """**出网脱敏的唯一入口。**

    ※ 全项目只有这一个函数被允许在「发出去之前」被调用。检查与脱敏必须
    复用**同一条判据** —— 另写一套的话两者迟早漂移，漂移后检查报「0 命中」
    而实际有东西出去了。
    所以审计读的是本函数返回的 `ScrubReport`，而不是自己再扫一遍。

    `known_uins`：本机已知的**账号**（uin 是数据源给的稳定数字 ID）。
    它们同样是「指得到具体人」的东西，所以走**姓名那条路** ——
    精确子串替换，出现在哪里都抹（包括 URL 里的）。
    """
    out = normalize(text)

    # 顺序：先抹号码，再抹姓名。
    # 为什么这个顺序：姓名可能**包含**数字（少见），而号码不会包含姓名。
    # 先抹号码，就不会出现「姓名被替换成 <姓名> 之后，里面的数字逃过检查」
    # 这种形状（虽然 `<姓名>` 里没有数字，但保持一个方向总是安全的）。
    out, num_hits = _mask_numbers(out)

    name_hits: list[ScrubHit] = []
    checked = 0
    all_names = list(names)

    # 已知 uin 进姓名名单 —— 它们同样是「指得到具体人」的东西。
    # ※ 只管 ≥ 5 位的（与**信号 C** 的下界一致）：短数字（如 uin=7）满地都是，
    # 抹了会把正文咬得稀烂。
    for uin in known_uins:
        s = str(uin)
        if len(s) >= 5:
            all_names.append(s)

    if all_names:
        # ※ **昵称是「全称」，正文是「裸名」** —— 两者必须能对应得上：
        # 拿全称去匹配正文，一个字都命中不了。
        #
        # 名单里给的是 `22-3班学习委员林小满`，而正文写的是 `林小满`。
        # 只拿全称做精确子串匹配，`林小满` **永远匹配不上** ——
        # 于是姓名脱敏在真实语料上等于没开，而它看起来是「配置了名单」。
        #
        # ⇒ 从每个昵称里**再拆出人名本体**，两样都进名单。
        out, name_hits, checked = mask_names(out, _expand_names(all_names))
    else:
        # ※ 名单为空时**也要有东西可查**：`checked = 0` 本身就是结果。
        # 别在这里短路返回一个「干净」的报告 —— 那正是「恒定报绿」。
        out, name_hits, checked = mask_names(out, [])

    report = ScrubReport(
        hits=num_hits + name_hits,
        names_checked=checked,
        num_placeholders=sum(
            1 for h in num_hits if h.kind in {"phone", "long_digits", "email", "account"}
        ),
        name_placeholders=len(name_hits),
    )
    return out, report


