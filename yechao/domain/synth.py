"""合成语料 —— 演示数据，同时是**唯一能给出真值的评测集**。

## 为什么这个文件必须存在（这是设计，不是便利）

**真实数据没有真值** —— 隐私
原因下永远无法人工标注。所以「漏检率」「幻觉率」这类端到端指标的分母与
标注，只能来自合成数据。

于是合成语料不只是「演示用的假数据」。**它是评测集。** 给每条语料带上真值
（这条该判成什么类、它的时间信息是明写的还是隐含的、它该不该被预筛丢掉），
成本极低，收益是一个可复现的、有标准答案的评测集。

## 假号码、假姓名、假群号**全部在这里自己编**

⚠️ 这是本项目的红线之一。它们**不必像真的**，
**格式对就够** —— 判据是按格式写的，不是按真实性写的。

本文件里的每个号码都是由**明确编号**（`N01`…）拼出来的，不是从任何地方
抄的。姓名用的是极常见的假名，群名一律以「示例·」开头。

## 真值怎么用

`CorpusMessage.expect` 是**标准答案**。指标脚本拿它跟模型/流水线的实际产出
对比 —— 而不是拿「模型说了什么」当指标。

⚠️ 真值要细到**能区分语义**的程度：
「源文里有一个日期」这句话不够 —— 必须说清它是**截止日**还是**活动开始**，
因为这两种落到不同字段上。所以 `expect.deadline_text` 与
`expect.start_text` 是**两个**字段，不是一个 `has_date` 布尔。
"""

from __future__ import annotations

from dataclasses import dataclass, field

from yechao.domain.models import PendingMessage


@dataclass(frozen=True)
class GroupSpec:
    """一个示例群。`tier` 是配置里的键名之一（`high` / `normal` / `low`）。"""

    id: int
    name: str
    tier: str
    #: 成员昵称表 —— 姓名脱敏的**名单来源**。
    #: ⚠️ 昵称在**本机内部**保留（它是判断「是不是官方发的」的信号），
    #: 只在**出网那一刻**才抹掉人名本体。
    nicknames: tuple[str, ...] = ()


@dataclass(frozen=True)
class Expect:
    """一条语料的**真值**。

    ⚠️ 这是「本该被怎么判」，不是「它看起来是什么」。指标脚本拿它做分母/标注。
    """

    #: 预筛该不该保留。`False` = 纯噪声，应当被丢弃规则命中。
    keep: bool = True
    #: 该判成哪个类目（slug）。`None` = 这条不该产出条目。
    kind: str | None = None
    #: 该有标题里的关键词（给「回连来源」判据用）。
    title_hint: str = ""
    #: **截止日**的原文写法。`None` = 源文里没有截止日。
    #: ⚠️ 与 `start_text` 分开 —— 混着算会让「模型把开始时刻正确填进 start
    #: 却被判成没填截止日」。
    deadline_text: str | None = None
    #: **活动开始时刻**的原文写法。`None` = 源文里没有开始时刻。
    start_text: str | None = None
    #: 地点原文。
    place_text: str | None = None
    #: 金额原文。
    amount_text: str | None = None
    #: ⚠️ 这条的绝对时刻**推不出来**（源文只给了相对时间）。它**不进**
    #: 「时刻抽取」的分母 —— 见  3：拿一个结构性达不到的
    #: 标准去衡量，等于给自己造一个假缺陷。
    start_not_inferable: bool = False
    #: 这条真值里含的号码（**为了断言它们必须被抹掉**）。
    numbers: tuple[str, ...] = ()
    #: 这条真值里含的姓名（同上）。
    names: tuple[str, ...] = ()
    #: 这条是**跨群转发**的（三条不同的消息说同一件事）。
    #: ⚠️ 转发**不是**刷屏 —— 那恰恰是最该保留、最该合并的信号。
    forwarded_from: str | None = None


@dataclass(frozen=True)
class CorpusMessage:
    msg: PendingMessage
    expect: Expect
    #: 给测试读的人类可读说明（「这条考的是什么」）。
    note: str = ""


