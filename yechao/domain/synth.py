#
# 姓名一律是极常见的假名，群名一律挂在虚构的「青梧」校名下。


def _m(
    msg_id: int,
    group_id: int,
    ts: int,
    sender: str,
    content: str,
    expect: Expect,
    note: str = "",
    account: int | None = None,
) -> CorpusMessage:
    return CorpusMessage(
        msg=PendingMessage(
            msg_id=msg_id,
            group_id=group_id,
            ts=ts,
            sender=sender,
            content=content,
            actor_account=account,
            # ※ 合成语料的来源**就是它自己**，不是某一个真实平台的源。
            # 不写这一项的话，这些消息会顶着默认值出现在审计里 ——
            # 一条格式完全正常、内容完全错的来源记录。
            source="synth",
        ),
        expect=expect,
        note=note,
    )


# 2026-10-18 09:00 的 Unix 秒（基准时刻，全部语料相对它偏移）
_T0 = 1792333200


def _at(hours: int = 0, minutes: int = 0) -> int:
    return _T0 + hours * 3600 + minutes * 60


