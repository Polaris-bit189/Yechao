def messages() -> tuple[PendingMessage, ...]:
    """演示与评测用的全部消息。"""
    return tuple(c.msg for c in CORPUS)


def expectations() -> dict[int, Expect]:
    """`msg_id → 真值`。指标脚本读它。"""
    return {c.msg.msg_id: c.expect for c in CORPUS}


def nicknames() -> list[str]:
    """全部群的成员昵称 —— 姓名脱敏的名单来源。"""
    out: list[str] = []
    for g in GROUPS:
        out.extend(g.nicknames)
    return out


def group_names() -> dict[int, str]:
    return {g.id: g.name for g in GROUPS}
