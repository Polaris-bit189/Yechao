# ── 构造器 ──────────────────────────────────────────────────────────


def render_categories(categories: list[Any]) -> str:
    """把类目表渲染成提示词里的那一段。

    ※ **只有这一处渲染** —— 抽取与云端复核共用它。分成两份写，改了一处漏
    另一处，症状是「本地判得对、云端判得不对」，而两份代码单看都对。

    slug 用反引号包起来是有意的：它告诉模型「这是要原样回填的字面量」，
    而不是一个可以翻译成中文的标签。少了反引号，模型会回填 label。
    """
    return "\n".join(f"- `{c.slug}`（{c.label}）：{c.desc}" for c in categories)


def example_kind(categories: list[Any]) -> str:
    """示例里那个 `kind` 的值 —— 取本批类目表的**第一个** slug。

    ※ 为什么不在提示词里写死一个 slug：类目表是**用户可编辑的数据**，写死的
    那个迟早会不存在（改名、删除）。而提示词里留着一个不存在的 slug，是在
    教模型一个不存在的类目 —— 它照着回填，`resolve_kind` 不报错，界面上
    出现一个没人认识的类目名。

    ※ 类目表为空时返回一个**显眼的中文占位**，不是空串 —— 空串会让示例变成
    `"kind": ""`，那看起来像「这一类就是空的」，而真相是配置没读到。
    """
    return categories[0].slug if categories else "（本批类目表为空）"


def build_extract_system(categories: list[Any]) -> str:
    """把**用户可编辑的**类目判据拼进提示词。

    ※ 这里就是「类目判据会逐字进提示词」的落点。类目表来自配置（用户能在
    网页上改），所以提示词不是常量 —— 它是一个函数。

    ※ 模板里有两个占位符（`{categories}` / `{example_kind}`），都得填。
    漏填会**抛 KeyError** —— 这是有意的：宁可炸在启动时，也不要发一段
    写着字面量 `{categories}` 的提示词出去（模型照样会回一段形状完美的
    JSON，只是类目判据整块丢了）。
    """
    return EXTRACT_SYSTEM.format(
        categories=render_categories(categories),
        example_kind=example_kind(categories),
    )


def build_extract_user(messages: list[Any], scrubbed: list[str]) -> str:
    """拼抽取的 user 部分。

    `scrubbed` 是**已被脱敏**的正文（与 `messages` 一一对应）。

    ※ 传进来的必须是脱敏后的 —— 这个函数**不自己脱敏**，因为脱敏的报告
    要单独落审计，混在这里做会让审计与出网**不是同一次动作**。

    ## ※ `messages` 里的 `sender` 也必须是脱敏后的（这条是补上的）

    **观察到什么现象**：下面这一行原来直接拼 `m.sender`，而 `m.sender` 是
    **群昵称** —— 真实语料里它长成「22-3班学习委员李青萝」，**人名就在里面**。
    后果是同一行里正文的姓名被抹成了 `<姓名>`，消息头上的「学习委员李青萝」
    却原样出网：一个**看起来已经脱敏**的提示词，漏了最直接的那一处人名。
    而它正是本项目核心叙事（「只有脱敏后的结果离开这台机器」）要防的事。

    **为什么这么定**：出网的每一段文本都必须来自 `scrub()`，而 `scrub()` 的
    报告必须落进**同一条**审计记录。所以发送者的脱敏只能发生在调用方
    （`extract._run_batch`）—— 与正文那一次调用挨着，两份报告合进同一条记录。
    本函数若自己再调一次 `scrub()`，审计与出网就分成两次动作了。

    **怎么验证**：调用方传进来的消息是
    `dataclasses.replace(m, sender=scrub(m.sender, names)[0])` 的产物
    （见 `extract._with_scrubbed_sender`）。两个方向都钉住了 ——
    出网文本里没有裸名，且审计记录的 `name_placeholders` 把发送者那一处
    也算进去（`tests/application/test_privacy_and_metrics.py`）。

    ## `[编号]` 这个前缀在传达什么

    `[msg_id]` 是**给读日志的人**看的（一条出网记录要能对上本机的那条消息），
    抽取的输出里**没有**对应的回填字段 —— 回连靠的是 `quote` 逐字匹配。
    留着它是因为两处调用点都钉在这个形状上，而且它让模型知道「这些行是
    一批有界的消息」。
    """
    blocks: list[str] = []
    for m, text in zip(messages, scrubbed):
        blocks.append(f"[{m.msg_id}] {m.sender}: {text}")
    return EXTRACT_USER_TEMPLATE.format(content="\n".join(blocks))


def build_digest_user(items: list[Any], material: str) -> str:
    """拼日报的 user 部分。

    ※ `material` 由 `domain/digest.py::build_model_input` 生成 ——
    **没依据的截止日在那一步就被摘掉了**。本函数只做拼接，不做判断。

    ※ **`material` 里必须带上每条的 `item_id`**：`parse_digest_lines` 按编号
    回连，回连不上的行会被丢掉（`application/digest.py` 用
    `k in valid_ids` 过滤）。模型看不到编号就写不出编号 —— 而它编一个，
    同样会被过滤掉，症状是「模型跑了，但一行都没用上」，与「模型没跑」在
    报告里长得一样。
    """
    return DIGEST_USER_TEMPLATE.format(content=material)


def parse_digest_lines(raw: str) -> dict[int, str]:
    """解析日报的模型输出。`{item_id: line}`。

    ※ 编号对不上的**丢掉** —— 回连不上的东西不能进产出。

    ※ 这里**复用** `extract.parse_candidates` 里那个 `_loads_first_json`：
    日报与抽取两路的模型输出形状相同（都可能带围栏、都可能前后有废话），
    而「取第一个完整 JSON」这件事**只该有一处实现**。

    这不是省几行代码 —— 是因为原来两边各写了一份「头切第一个 `[`、
    尾切最后一个 `]`」，而那份实现**有一个 bug**（见
    `extract._loads_first_json` 的 docstring：它会把自己的合法输出咬坏）。
    两份实现在同一处出错，其中一份修了另一份没修 —— 那正是
    「两边各写一份必漂移」最典型的样子。
    """
    from yechao.application.extract import _NOTHING, _loads_first_json

    data = _loads_first_json(raw.strip())
    if data is _NOTHING or not isinstance(data, list):
        return {}

    out: dict[int, str] = {}
    for row in data:
        if not isinstance(row, dict):
            continue
        try:
            iid = int(row.get("item_id"))
        except (TypeError, ValueError):
            continue
        line = str(row.get("line") or row.get("text") or "").strip()
        if line:
            out[iid] = line
    return out
