"""提示词 —— 抽取与日报两套。

## 要防哪三类错

这是本模块存在的全部理由。每一段提示词都在防下面某一类：

**一、抄错原文。** 模型把「10月28日」写成「10月29日」，或者把三条消息的内容
揉成一条。⇒ 对策：要求它给出**逐字摘录**，而程序拿摘录去源文里找。

**二、补出源文没有的字段。** 源文写「明早集合」，它填一个具体时刻；写
「押金照旧」，它编一个金额。⇒ 对策有三层，缺一不可：
  · 提示词里**要求**「找不到就别填」
  · 输出格式里那几格是**可选**的（不是必填）—— 「必填」是在**逼它编**
  · 闸门（`verify.py`）在写入边界**复核**

⚠️ **第三层不能省。** 提示词是「请求模型别犯错」，闸门是「我们不信它」。
只有请求没有复核，等于把判据交给一个不能写测试的东西。

**三、把发送者身份当成类目依据。** 发消息的人是「班主任」不代表这条消息
就是「通知公告」—— 类目看的是**这条消息要读者做什么**。

## 为什么类目判据要「逐字进提示词」

`web/src/types.ts` 的 `CategoryDetail.desc` 注释：**「类目判据，会逐字进提示词。
编辑器必须能改它。」** ⇒ 类目表是可编辑的**数据**，不是硬编码的提示词片段。

这条设计的影响：提示词不能把七条判据写死在里面，必须**拼**进去。
好处是用户在网页上加了第八个类目，提示词**自动**就认它。

## 「截止日」与「开始时刻」怎么在提示词里分开

这里要问：光说「别混」够不够？——**不够。**

「别混」是一句**否定指令**，而模型没有「混」这个概念。有用的是**给出对照**：

```
截止日：要在那个日期之前**办完**某件事   → "9月30日前交材料"
开始时刻：那个时刻**去某个地方参加**某件事 → "9月30日 14:00 在报告厅集合"
```

⚠️ 对照例必须是**同一日期**的两种用法（都是 9月30日）—— 那才是它们最容易
混的地方。用两个不同的日期做例，模型学不到区别。

## 为什么输出示例里 `deadline` 可以是 `null`

见上面「二」：可选字段的语法形式本身就是一条指令。
把 `"deadline": "2026-09-30"` 写成必填，模型会**倾向于填一个**（填空比留空
在语言模型里更「安全」）。所以示例里显式给出 `null` 的样子。
"""

from __future__ import annotations

from typing import Any

# ── 抽取 ────────────────────────────────────────────────────────────

#: 抽取的输出预算。
#:
#: ⚠️ **思考型模型的预算要同时装下思考与正文**，而思考长度随输入规模增长。
#: 实测（qwen3:8b / Ollama）：8192 在较长的批上仍会被思考吃光 ——
#: 表现为 `finish_reason=length` 且 `content` 为空。
#:
#: 这个失败**特别具有欺骗性**：它看起来像「模型不会干活」或「提示词不好」，
#: 而真相只是预算不够。所以这个数取得宽松（32768），
#: 而真撞上限时错误消息会报出实际写出多少字。
EXTRACT_MAX_TOKENS = 32768

EXTRACT_SYSTEM = """你是一个校园通知整理助手。输入的是一段群聊记录，你要从中找出「需要读者去做/知道的事」，整理成结构化条目。

## 什么该整理成条目

一条消息**要读者做一件事**（去报名、去参加、去领取、去买、去找失主）或者
**要让读者知道一个安排**（放假、调课、系统维护）时，它是条目。

「收到」「好的」「哈哈哈哈」这类**应答**不是条目，直接跳过。

## 类目怎么判

看这条消息**要读者做什么**，**不要**看它出现了哪个词。

例如「讲座通知：请于周五前报名」——它出现了「讲座」（像活动），但它要读者
**去报名**（一件有截止的事），所以它是「学业」类，不是「活动」类。

可用的类目：

{categories}

## 字段怎么填

**摘录（quote）**：从输入里**逐字**复制一小段原文（8-30 字），必须与输入
一字不差。程序要用它把你这条条目指回原始消息。

**标题（title）**：不超过 20 字的概括，是**你自己的话**，不是摘录。

**详情（detail）**：一到两句补充说明。没有就填 null，不要硬凑。

**截止日（deadline）**：要在那个日期之前**办完**某件事时填。
  例：`9月30日前交材料` → deadline 是 9月30日

**开始时刻（start）**：那个时刻**去某个地方参加**某件事时填。
  例：`9月30日 14:00 在报告厅集合` → start 是 9月30日 14:00

⚠️ 这两个字段最容易混。区别是**「办事的期限」还是「到场的时间」**：
  · 交作业、报名、缴费 → 是**期限** ⇒ deadline
  · 集合、讲座、比赛、摆摊 → 是**到场时间** ⇒ start

**地点（place）**：原文里出现的地点名。没有就 null。

**金额（amount）**：原文里的价格，连单位一起抄（如 `30元`）。没有就 null。

## ⚠️ 最重要的一条

**源文里没有的字段，一律填 null。不许推测、不许补全、不许算。**

输入写「明早集合」——**你就填不了 start**，因为原文没有具体时刻。填 null。
输入写「押金照旧」——**你就填不了 amount**。填 null。

**编一个看起来合理的值，比留 null 坏得多**：那个值会进日历、进日报，
读者会照着它去行动。

## 输出格式

只输出 JSON 数组，不要任何解释文字：

```json
[
  {{
    "kind": "academic",
    "title": "期中教学检查材料提交",
    "quote": "请各班于10月28日前提交教学检查材料",
    "detail": "逾期不予受理。",
    "deadline": "10月28日",
    "start": null,
    "place": null,
    "amount": null
  }}
]
```

⚠️ 注意上面示例里 `start` / `place` / `amount` 都是 `null` —— 因为那段原文
里没有这些信息。**这就是正确的填法。**
"""


EXTRACT_USER_TEMPLATE = """以下是待整理的群聊记录。请按系统提示的格式输出 JSON 数组。

{content}
"""


# ── 日报 ────────────────────────────────────────────────────────────

#: 日报的输出预算。
#:
#: ⚠️ 这个数**比抽取大得多**，理由是实测出来的（不是猜的）：
#:
#: 日报的输入是一份**条目清单**，而思考型模型的思考长度**随输入规模增长**。
#: 实测 88 行的输入（9 条条目 × 每条约 10 行）要花掉 8192 token 以上的思考，
#: 正文一个字还没开始写 —— 于是 `finish_reason=length`、`content` 为空。
#:
#: ⇒ 32768。这个数覆盖了「思考 + 正文」，并且给条目更多的日子留了余量。
#: 真撞上限时，`ModelTruncated` 会报出实际用了多少（见 `got_chars`）。
DIGEST_MAX_TOKENS = 32768

DIGEST_SYSTEM = """你是一份校园日报的编辑。输入是今天已经整理好的条目清单，
你要为**每一条**写一句话，让读者一眼知道「这条要不要管、要管的话做什么」。

## 怎么写

- **一条一行，不要合并、不要漏。** 输入的每一条都要有对应的输出。
- 一句话，不超过 40 字。
- 写**要读者做的事**，不要复述标题。
  · 好：`10月28日前交材料，逾期不受理`
  · 差：`期中教学检查的通知`
- 只有输入里给了截止日/开始时刻，才能写进你这句话。
  ⚠️ **输入里没有的日期，一个字都不许写。**
- 不要用 emoji，不要用 markdown 记号。

## 输出格式

只输出 JSON 数组：

```json
[
  {{"item_id": 12, "line": "10月28日前交材料，逾期不受理"}},
  {{"item_id": 13, "line": "今天 14:00 图书馆门口摆摊招新"}}
]
```

`item_id` 必须与输入里给出的编号一致。**对不上编号的那一行会被丢掉。**
"""


DIGEST_USER_TEMPLATE = """以下是今天的条目清单。请为每一条写一句话。

{content}
"""


# ── 构造器 ──────────────────────────────────────────────────────────


def build_extract_system(categories: list[Any]) -> str:
    """把**用户可编辑的**类目判据拼进提示词。

    ⚠️ 这里就是「类目判据会逐字进提示词」的落点。类目表来自配置（用户能在
    网页上改），所以提示词不是常量 —— 它是一个函数。
    """
    lines: list[str] = []
    for c in categories:
        lines.append(f"- `{c.slug}`（{c.label}）：{c.desc}")
    return EXTRACT_SYSTEM.format(categories="\n".join(lines))


def build_extract_user(messages: list[Any], scrubbed: list[str]) -> str:
    """拼抽取的 user 部分。

    `scrubbed` 是**已被脱敏**的文本（与 `messages` 一一对应）。
    ⚠️ 传进来的必须是脱敏后的 —— 这个函数**不自己脱敏**，因为脱敏的报告
    要单独落审计，混在这里做会让审计与出网**不是同一次动作**。
    """
    blocks: list[str] = []
    for m, text in zip(messages, scrubbed):
        blocks.append(f"[{m.msg_id}] {m.sender}: {text}")
    return EXTRACT_USER_TEMPLATE.format(content="\n".join(blocks))


def build_digest_user(items: list[Any], material: str) -> str:
    """拼日报的 user 部分。

    ⚠️ `material` 由 `domain/digest.py::build_model_input` 生成 ——
    **没依据的截止日在那一步就被摘掉了**。本函数只做拼接，不做判断。
    """
    return DIGEST_USER_TEMPLATE.format(content=material)


def parse_digest_lines(raw: str) -> dict[int, str]:
    """解析日报的模型输出。`{item_id: line}`。

    ⚠️ 编号对不上的**丢掉** —— 回连不上的东西不能进产出。

    ⚠️ 这里**复用** `extract.parse_candidates` 里那个 `_loads_first_json`：
    日报与抽取两路的模型输出形状相同（都可能带围栏、都可能前后有废话），
    而「取第一个完整 JSON」这件事**只该有一处实现**。

    这不是省几行代码 —— 是因为原来两边各写了一份「头切第一个 `[`、
    尾切最后一个 `]`」，而那份实现**有一个 bug**（见
    `extract._loads_first_json` 的 docstring：它会把自己的合法输出咬坏）。
    两份实现在同一处出错，其中一份修了另一份没修 —— 那正是
    「两边各写一份必漂移」最典型的样子。
    """
    from yechao.application.extract import _NOTHING, _loads_first_json

    data = _loads_first_json(raw.strip())
    if data is _NOTHING or not isinstance(data, list):
        return {}

    out: dict[int, str] = {}
    for row in data:
        if not isinstance(row, dict):
            continue
        try:
            iid = int(row.get("item_id"))
        except (TypeError, ValueError):
            continue
        line = str(row.get("line") or row.get("text") or "").strip()
        if line:
            out[iid] = line
    return out
