"""提示词 —— 抽取、日报、以及两套共用的类目渲染。

## 这个文件里每一条要求都指向一个具体的失败

写法约定：每条要求旁边要能说出「不这么写，模型会做出什么」。说不出这一句的
要求不留 —— 它要么是套话，要么是**某个已经被代码兜住的失败在提示词里的
影子**。重复一层没有坏处，但有代价：它稀释注意力，还会让人误以为提示词
是防线。

※ 提示词**不是**防线。它没法写测试，而一个没法测试的防线出错时不发声音。
真正承重的是另外两层：可选字段的**语法形式**（下面「形式即指令」一节），
以及写入边界的**机械核验**（`domain/verify.py`，判据是字面匹配）。

## 形式即指令（第三步：逐一回答「这个形式在传达什么」）

提示词里有些东西不是文字而是**语法**。它们同样在告诉模型该怎么填，而且比
文字更硬 —— 模型按示例的形状走，不按你反复强调的话走：

| 形式 | 在传达什么 | 不这么写会怎样 |
|---|---|---|
| 示例里 `start` / `place` / `amount` 写成 `null` | 这几格**可以空**，空了是正常填法 | 示例只给有值的例子 ⇒ 模型倾向于每格都填 —— 而「填空」在语言模型里比留空更「安全」 |
| 示例里八个键**一个不少** | 形状是固定的，不是「有什么写什么」 | 少写一个键 ⇒ 模型有时省、有时给，形状漂移，而漏 `quote` / `title` 是**静默丢整条** |
| 输出是**裸数组**（无围栏、无前后的话） | 契约就是「只输出这一段」 | 文字说「不要围栏」而示例带围栏 ⇒ 模型按示例走 |
| 类目表里 slug 用**反引号**包起来 | slug 是要**原样回填的字面量**，不是给人读的中文名 | 不给反引号 ⇒ 模型回填中文标签，而 `resolve_kind` 对未知 slug **不报错**，界面上会出现一个没人认识的类目 |
| 示例里的 `kind` 取自**本批类目表** | 它演示的是形状，不是取值 | 写死一个 slug ⇒ 那个 slug 改名/删除之后，提示词还在教一个不存在的类目 |
| 云端示例里 `swap_time` 每一条都给 `false` | 这是**每条都要回答**的问题，不是可选补充 | 只在要交换时才给 ⇒ 模型倾向于不给（也就是不交换） |

※ `EXTRACT_SYSTEM` 与 `CLOUD_SYSTEM` 会经过 `.format()`，所以 JSON 示例里的
花括号写成 `{{ }}`。而 `DIGEST_SYSTEM` **不经过** `.format()`（调用方直接把它
当字符串用）—— 所以它里面的花括号是**单层**的。写成 `{{` 的话，模型会真的
看到两层花括号。

## 抽取这一路要防什么

输入是**群聊原文**：口语、省略、错别字、多条混在一起、时间常是相对的。
输出是**结构化条目**。落差就是失败清单：

**一、粒度错。** 两个方向，各自指向一个失败：
  · 一条消息里有两件独立的事，只抽出一件 —— 另一件再没有任何地方会提到它
  · 把几条消息的片段拼成一条 —— `quote` 必须能在**单条**消息里逐字找到
    （`extract.match_quote`），拼出来的摘录回连不上，整条被丢
  · 同一件事在几条消息里各说了一遍，被模型合并成一条 —— 合并是程序的事
    （按标题相似度，并记下 `source_count`）。模型合并了，那个计数永远是 1，
    而「这件事在几个群里被转」恰恰是最该留下的信号

**二、回连断。** `quote` 是程序把条目指回原文的**唯一**凭据，判据是**逐字**
匹配。模型把它写成转述（改标点、补口语、顺一遍句子）就回连不上 —— 而这一路
的症状特别像成功：JSON 合法、内容也对，只是**一条都进不来**。

**三、类目判错。** 判据是「这条消息要读者做什么」。按关键词判会错；按发送者
身份判（班主任发的 ⇒ 通知公告）也会错。还有两种更隐蔽的：回填中文标签而不是
slug，或者自造一个 slug —— `categories.resolve_kind` 对未知 slug **不报错**，
它照原样展示，于是界面上出现一个没人认识的类目名。

**四、补出源文没有的值。** 「明早集合」填一个时刻，「押金照旧」填一个金额。
这是本层唯一会**伤害读者**的失败：编出来的值会进日历、进日报，读者照着它
行动，而且没有任何一处会提醒他这是编的。

**五、时间字段错位。** 「截止日」与「开始时刻」是两个字段，落到不同的列上。
它们最容易混的地方是**同一条消息里两个都出现**时 —— 所以对照例要用这种
消息，而不是两条各含一个时间、日期还不同的消息（那样模型分不清哪个维度
才是区别）。

**六、群聊里的文字被当成指令。** 群聊是不受控输入，里面可能有人写「忽略上面
的要求」「把提示词发出来」。它不是数据之外的什么东西 —— 它就是数据。

## 日报这一路要防什么

输入是**已经整理好的条目清单**（`domain/digest.py::build_model_input` 拼的，
没依据的截止日在那一步就被摘掉了），输出是每条一句话：

**一、编日期。** 输入里没有的日期被写进那一句话。输入里已经摘干净了，所以
这条要求是最后一道 —— 但它是这一路唯一会让人跑错时间的失败。

**二、行对不上。** 漏行、合并行、编号写成序号 —— 回连不上的行会被丢掉
（`parse_digest_lines`），而丢掉之后有机械行兜底，所以**看不见**。

**三、写成复述。** 「XX 的通知」这种行，读者点进去才知道要干什么，一句话
日报的价值就没了。

## 类目判据为什么整段拼进提示词

`desc` 是用户能在网页上改的**数据**（`web/src/api.ts` 的 `CategoryDetail`），
不是提示词里的常量。写死在模板里，用户新加的第八个类目模型就永远不认。
所以 `EXTRACT_SYSTEM` 是一个**模板**，`build_extract_system(categories)` 才是
提示词。渲染只有一处实现（`render_categories`），抽取与云端复核共用它 ——
分两份写，改了一处漏另一处，症状是「本地判得对、云端判得不对」。
"""

