r"""时间解析 —— 边界、跨行、中文数字、年份。

## 这个文件在钉什么

`times.py` 是**核验闸门的地基**：闸门问「模型填的这个月日，源文里有没有」，
而「有没有」是靠这个模块把两边映到同一个坐标系里判的。所以这里的每一条判据
都直接决定闸门会不会**放行一个源文里没有的日子**，或者**清掉一个源文里有的日子**。

三件事：

  1. **边界**：一个日期/时刻是一个 **token**，两侧都不能紧邻数字。
     这是本文件的核心 —— `11/25` 不许给 `11/2` 背书。
  2. **跨行**：`\s*` 允许月与日之间换行。这是**允许**，不是 bug ——
     理由与前提写在 `times.py` 的「跨行」一节。
  3. **裸日不算日期**：本模块只认「月 + 日」齐备的日期。
     `28日` 没有月份，于是它不产出命中，也就不会给任何日期背书。

※ 样本全部自己编（`11/25`、`7点40分`、`十月二十八日` 这类是**格式**，
不是任何一批真实数据）。
"""

from __future__ import annotations

from yechao.domain.times import (
    find_date_literal,
    find_dates,
    find_time_literal,
    find_times,
    has_relative_day,
)

# ── 数字边界：日期是一个 token，两侧不能紧邻数字 ────────────────────


def test_斜杠日期_长月日不给短月日背书() -> None:
    """※ **本文件的核心判据。**

    `11/25` 里含 `11/2`。判据若按「子串在不在」写，源文写着 `11/25` 就会给
    模型填的 `11/2` 背书 —— 而 11 月 2 日与 11 月 25 日是**两个不同的日子**。
    用户按错的那个去办，会错过期限。

    解法是**边界**：`/25` 之后不是数字 ⇒ 通过；`/2` 之后是 `5` ⇒ 拒绝。
    """
    assert find_date_literal("11/25 截止", 11, 2) is None
    assert find_date_literal("11/25 截止", 11, 25) == "11/25"


def test_斜杠日期_左边界也挡住() -> None:
    """左侧同样是判据：`811/25` 里的 `11/25` 不是这个日期。

    （`11` 与 `811` 是两个不同的数，同理 `/25` 与 `/2` 也是。）
    """
    assert find_date_literal("编号811/25 归档", 11, 25) is None


def test_时刻_长分钟不给短分钟背书() -> None:
    """同一条边界在**时刻**上更隐蔽，因为「分」这个字把边界藏了起来。

    源文写 `7点40分`，模型填 `7点4分`：`4` 之后是 `0`（数字）⇒ 拒绝。
    而源文真的写 `7点4分` 时，`4` 之后是「分」（非数字）⇒ 通过。
    """
    assert find_time_literal("7点40分集合", 7, 4) is None
    assert find_time_literal("7点40分集合", 7, 40) == "7点40分"
    assert find_time_literal("7点4分集合", 7, 4) == "7点4分"


def test_冒号时刻的分钟不按位数判() -> None:
    """※ 判据是**两侧**，不是「分钟必须两位」。

    `14:5` 是 `14:05` 的一种合法写法（人确实会这么打），它必须被认出来；
    而 `14:50` 里那个 `14:5` **不是** `14:5` —— 右侧的边界已经判掉了。
    """
    assert find_time_literal("14:5 集合", 14, 5) == "14:5"
    assert find_time_literal("14:50 集合", 14, 5) is None
    assert find_time_literal("14:05 集合", 14, 5) == "14:05"


def test_短月日也是日期_长度不是判据() -> None:
    """`3/7-3/9` 是一个日期**区间**，两个端点都只有一位月/日。

    ⇒ 「短」不是拒绝的理由。判据用的是边界，长度只是它的副作用。
    """
    hits = find_dates("3/7-3/9 报名")
    assert [(h.month, h.day) for h in hits] == [(3, 7), (3, 9)]


def test_越界的月日不产出命中() -> None:
    assert find_dates("13月40日") == []
    assert find_dates("10月32日") == []


# ── 裸日不算日期 ────────────────────────────────────────────────────


def test_裸日不产出命中_也不给任何日期背书() -> None:
    """※ 源文只写「28日」，没写月份。

    本模块只认「月 + 日」齐备的日期 ⇒ `28日` **不是**本模块意义上的日期，
    它既不产出命中，也就不会给模型填的 `10月28日` 背书。

    理由写在 `times.py` 的「裸日不算依据」一节：闸门只看得到消息正文、
    看不到消息的发出时刻，所以它**核对不了那个月份** ——
    而月份恰恰是错的来源（用户按错的月份去办会错过期限）。
    """
    assert find_dates("28日前提交材料") == []
    assert find_date_literal("28日前提交材料", 10, 28) is None


# ── 年份：源文写了的才核对 ──────────────────────────────────────────


def test_源文写了年份时_年份参与判据() -> None:
    """源文写 `2027年10月28日`、模型填 `2026-10-28` —— 这是**两个不同的日子**。

    不核对年份，就等于用前者的原文给后者背书。
    """
    assert find_date_literal("2027年10月28日截止", 10, 28, year=2027) is not None
    assert find_date_literal("2027年10月28日截止", 10, 28, year=2026) is None


def test_源文没写年份时_年份不参与判据() -> None:
    """源文里没写年份 ⇒ 年份是从消息时刻推的，不该因此判它没依据。

    两种调用方式都要成立：显式传年份、以及不传（`None`）。
    """
    assert find_date_literal("10月28日截止", 10, 28) == "10月28日"
    assert find_date_literal("10月28日截止", 10, 28, year=2026) == "10月28日"


def test_带年份的日期只出一个命中() -> None:
    """`2027年10月28日` 会被「完整日期」与「月日」两条形态同时看到，
    但重叠的取先长后短 ⇒ **只出一个**命中，且带年份。"""
    hits = find_dates("2027年10月28日截止")
    assert len(hits) == 1
    assert (hits[0].year, hits[0].month, hits[0].day) == (2027, 10, 28)


def test_不带年份的日期_year为None() -> None:
    """※ `year is None` 是**信号**，不是缺省：源文没写年份时，年份要由
    调用方从**消息发出时刻**补（领域层不取当前时刻）。"""
    hits = find_dates("10月28日截止")
    assert hits[0].year is None


# ── 跨行：这是 `\s*` 那条判据 ───────────────────────────────────────


def test_跨行日期仍算一个日期() -> None:
    """※ **实测：`find_dates("10月\\n28日")` 命中 10 月 28 日。**

    结论是「**不是 bug**」，理由写在 `times.py` 的「跨行」一节：调用方
    （`extract._resolve_ts` 与 `verify.gate`）喂进来的是**单条消息的正文**，
    而一条消息内部换行是**合法排版**（群公告常写「报名截止：10月\\n28日」）。
    换行在这里是标点，不是消息边界。

    所以这个测试断言的是**允许跨行**，而不是「修好了不再跨行」。
    """
    hits = find_dates("报名截止：10月\n28日")
    assert len(hits) == 1
    assert (hits[0].month, hits[0].day) == (10, 28)
    assert "\n" in hits[0].raw  # 原文片段保留了换行 —— 闸门要能指着它说话


def test_跨行日期能被闸门的字面判据用上() -> None:
    """跨行命中要能一路走到 `find_date_literal` —— 那才是闸门真正调用的函数。

    只测 `find_dates` 不够：闸门用的是 `find_date_literal`，两者之间任何一层
    写歪，结论就落不到地。
    """
    assert find_date_literal("报名截止：10月\n28日", 10, 28) == "10月\n28日"


def test_同一条消息里的两个独立日期不互相吞并() -> None:
    """跨行允许，但**不**意味着相邻的日期会被并成一个。

    一条消息里写了两件事（`10月1日 报名` / `10月5日 截止`），必须出两个
    命中 —— 否则闸门会拿第一个日期给第二个日期背书。
    """
    hits = find_dates("10月1日 报名\n10月5日 截止")
    assert [(h.month, h.day) for h in hits] == [(10, 1), (10, 5)]


def test_换行紧跟在月之后才可能拼接() -> None:
    """※ 残余风险的边界（已知、可接受，写在 `times.py` 的「跨行」一节）。

    拼接要求换行**紧跟在「月」之后**。「10月表彰\\n28日交表」里「月」后面
    紧跟的是「表」而不是空白 ⇒ **不**命中，不会凭空造出一个 10 月 28 日。
    """
    assert find_date_literal("10月表彰\n28日交表", 10, 28) is None
    assert find_dates("10月表彰\n28日交表") == []


# ── 中文数字与时段词 ────────────────────────────────────────────────


def test_中文数字日期() -> None:
    assert [(h.month, h.day) for h in find_dates("十月二十八日")] == [(10, 28)]
    assert [(h.month, h.day) for h in find_dates("十月三日")] == [(10, 3)]
    # `十二` 是 12，不是「十」+「二」拼错
    assert [(h.month, h.day) for h in find_dates("十二月三十一日")] == [(12, 31)]


def test_中文数字时刻与时段词() -> None:
    """时段词把十二小时制补成二十四小时制；`半` 是 30 分。"""
    assert (find_times("下午两点")[0].hour, find_times("下午两点")[0].minute) == (14, 0)
    assert (find_times("九点半")[0].hour, find_times("九点半")[0].minute) == (9, 30)
    # ※ 源文里已经写 20 点还带「晚上」的情况存在 —— 不该再加 12
    assert find_times("晚上8点")[0].hour == 20
    # `凌晨12点` 其实是 0 点
    assert find_times("凌晨12点")[0].hour == 0


def test_时段词被吸进原文片段() -> None:
    """`raw` 要含时段词 —— 闸门指着源文说话时，「下午两点」比「两点」更能
    说明模型填的 14:00 是从哪来的。"""
    hit = find_times("下午两点")[0]
    assert hit.raw == "下午两点"
    assert hit.start == 0


# ── 相对日词 ────────────────────────────────────────────────────────


def test_相对日词命中并返回那个词() -> None:
    """闸门要指着那个词说话（「源文只有相对时间『明早』」），所以返回词本身，
    不是布尔。"""
    assert has_relative_day("明早七点在东门集合") == "明早"
    assert has_relative_day("请于10月28日前提交") is None


def test_相对日词取最长匹配() -> None:
    """※ `大后天` 里**含有** `后天`。

    按表里的顺序取，源文写「大后天」会被报成「源文只有相对时间『后天』」——
    一句**源文里没有的话**。证据必须能逐字对回源文，所以先试长的。
    """
    assert has_relative_day("大后天交表") == "大后天"
    assert has_relative_day("后天交表") == "后天"


def test_相对日词推不出绝对时刻() -> None:
    """「明早」在源文里，但 `08:00` 不在 ⇒ 它不是时刻**依据**。

    这条是给闸门的「不适用」态做地基：源文提到了时间，只是没精确到能填进
    `start_ts` 那一格。所以这里断言的是「`find_times` 不会从相对日词里
    凭空造出一个时刻」。
    """
    assert find_times("明早集合") == []
    assert find_date_literal("明早集合", 10, 28) is None


# ── 分母自检 ────────────────────────────────────────────────────────


def test_一条消息里的多个日期都被找出来_不是只找一个() -> None:
    """※ 空转自检：这条用例有**分母**。

    一个「只返回第一个命中」的实现能让上面大多数用例通过
    （它们大多只查一个日期）。这里要三个都出来。
    """
    hits = find_dates("11月2日报名，11月25日截止，12月1日公布")
    assert [(h.month, h.day) for h in hits] == [(11, 2), (11, 25), (12, 1)]
    assert find_times("9点集合，14:30 出发，晚上7点回来") != []
    assert len(find_times("9点集合，14:30 出发，晚上7点回来")) == 3
